/**
  * @brief This function handles UART8 global interrupt.
  */
void UART8_IRQHandler(void)
{
  /* USER CODE BEGIN UART8_IRQn 0 */

  /* USER CODE END UART8_IRQn 0 */
  HAL_UART_IRQHandler(&huart8); //
  /* USER CODE BEGIN UART8_IRQn 1 */

  // 检查 UART8 是否触发了 IDLE（空闲线路）中断
  // IDLE = 一帧数据发完后总线空闲超过 1 字节时间
  if (__HAL_UART_GET_FLAG(&huart8, UART_FLAG_IDLE)) {   // 判断是否为 IDLE 空闲中断（一帧数据接收完毕）
      __HAL_UART_CLEAR_IDLEFLAG(&huart8);    // 清除 IDLE 标志（读 SR + 读 DR，硬件规定）
      uart8_idle_flag = 1;        // 置标志位，通知主循环的函数去读环形缓冲区
      uart8_rx_count++;           // 【调试】IDLE 中断计数，Watch 窗口查看此变量
  }
  /* USER CODE END UART8_IRQn 1 */
}

